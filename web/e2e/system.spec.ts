import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { compare, fillFiles, register } from './helpers';

test('fluxo real: cadastro, arquivos, resultado, mapa, histórico, impressão, logout, login e isolamento de B', async ({ page, browser }) => {
  const account = await test.step('cadastro A', () => register(page));
  await fillFiles(page);
  await page.getByLabel('Método / apresentação').selectOption('all');
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/comparisons') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Comparar conteúdos' }).click();
  const response = await test.step('resposta da comparação', () => responsePromise);
  expect(response.status()).toBe(200);
  const saved = await response.json();
  expect(saved.result.state).toBe('calculated');
  expect(Number.isFinite(saved.result.index.value) && saved.result.index.value >= 0 && saved.result.index.value <= 100).toBe(true);
  await expect(page.getByRole('heading', { name: 'Relações entre os conteúdos' })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Sentenças: Fonte', exact: true }).getByText('O algoritmo funciona.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: /^Selecionar F1, A2,/ }).click();
  await expect(page.getByRole('heading', { name: 'Par selecionado: F1 × A2' })).toBeVisible();
  const sessionCookie = (await page.context().cookies()).find(cookie => cookie.name === 'hts_session');
  expect(Boolean(sessionCookie?.httpOnly && sessionCookie.sameSite === 'Strict' && !sessionCookie.secure)).toBe(true);
  const oldToken = sessionCookie!.value;
  await test.step('abrir histórico', () => page.getByRole('button', { name: 'Histórico', exact: true }).click());
  await expect(page.getByRole('heading', { name: 'Histórico', exact: true })).toBeVisible();
  await test.step('abrir resultado persistido', () => page.getByRole('link', { name: 'Abrir resultado', exact: true }).click());
  await expect(page.getByRole('heading', { name: 'Relações entre os conteúdos' })).toBeVisible();
  const persisted = await page.request.get('/api/comparisons/' + saved.id);
  expect(persisted.status()).toBe(200);
  const reread = await persisted.json();
  expect(JSON.stringify(reread.result) === JSON.stringify(saved.result)).toBe(true);
  const output = process.env.HTS_E2E_OUTPUT ?? 'artifacts/e2e';
  mkdirSync(output, { recursive: true });
  await page.emulateMedia({ media: 'print' });
  await expect(page.getByRole('button', { name: 'Imprimir relatório' })).toBeHidden();
  await expect(page.getByRole('heading', { name: 'Índice de similaridade híbrido', exact: true })).toBeVisible();
  await test.step('gerar PDF de impressão', () => page.pdf({ path: join(output, 'print.pdf'), format: 'A4', printBackground: true }));
  await test.step('voltar ao modo tela', () => page.emulateMedia({ media: 'screen' }));
  await test.step('viewport móvel', () => page.setViewportSize({ width: 390, height: 844 }));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2)).toBe(true);
  await test.step('capturar layout móvel', () => page.screenshot({ path: join(output, 'ui-mobile.png'), fullPage: true }));
  await test.step('logout', () => page.getByRole('button', { name: 'Sair', exact: true }).click());
  await expect(page.getByRole('heading', { name: 'Entrar', exact: true })).toBeVisible();
  expect((await page.request.get('/api/comparisons/' + saved.id)).status()).toBe(401);
  await test.step('URL direta sem sessão', () => page.goto('/results/' + saved.id));
  await expect(page.getByRole('heading', { name: 'Entrar', exact: true })).toBeVisible();
  await page.getByLabel('E-mail', { exact: true }).fill(account.email);
  await page.getByLabel('Senha', { exact: true }).fill(account.password);
  await test.step('login A', () => page.getByRole('button', { name: 'Entrar', exact: true }).click());
  await expect(page.getByRole('heading', { name: 'Relações entre os conteúdos' })).toBeVisible();
  expect((await page.context().cookies()).find(cookie => cookie.name === 'hts_session')?.value !== oldToken).toBe(true);
  const contextB = await browser.newContext({ baseURL: process.env.HTS_WEB_URL ?? 'http://127.0.0.1:3000' });
  const pageB = await contextB.newPage();
  await test.step('cadastro B', () => register(pageB));
  expect((await pageB.request.get('/api/comparisons/' + saved.id)).status()).toBe(404);
  const listB = await (await pageB.request.get('/api/comparisons')).json();
  expect(listB.items.length).toBe(0);
  await test.step('URL de A acessada por B', () => pageB.goto('/results/' + saved.id));
  await expect(pageB.locator('main .error[role="alert"]')).toContainText('comparação não encontrada');
  await expect(pageB.getByRole('region', { name: 'Sentenças: Fonte', exact: true })).toHaveCount(0);
  await contextB.clearCookies();
  await contextB.addCookies([{ name: 'hts_session', value: 'A'.repeat(43), url: process.env.HTS_WEB_URL ?? 'http://127.0.0.1:3000', httpOnly: true, sameSite: 'Strict' }]);
  expect((await pageB.request.get('/api/auth/session')).status()).toBe(401);
  await pageB.reload();
  await expect(pageB.getByRole('heading', { name: 'Entrar', exact: true })).toBeVisible();
  await contextB.close();
});

test('mapa lexical maior: paginação dos dois eixos e seleção por índices reais', async ({ page }) => {
  await register(page);
  await page.getByRole('button', { name: 'Texto colado', exact: true }).click();
  const sentence = 'A pesquisa compara conteúdos em português.';
  await page.getByLabel('Texto fonte', { exact: true }).fill(Array(7).fill(sentence).join(' '));
  await page.getByLabel('Texto analisado', { exact: true }).fill(Array(9).fill(sentence).join(' '));
  await page.getByLabel('Método / apresentação').selectOption('lexical');
  await compare(page, 200);
  await expect(page.getByRole('button', { name: /^Selecionar F7, A9,/ })).toHaveCount(0);
  await page.getByRole('button', { name: 'Próximas linhas', exact: true }).click();
  await page.getByRole('button', { name: 'Próximas colunas', exact: true }).click();
  await page.getByRole('button', { name: /^Selecionar F7, A9,/ }).click();
  await expect(page.getByRole('heading', { name: 'Par selecionado: F7 × A9' })).toBeVisible();
  await expect(page.getByText(/Matriz lexical; janela F7–F7, A9–A9/)).toBeVisible();
  await expect(page.getByRole('region', { name: 'Sentenças: Fonte', exact: true }).locator('.sentence.selected .sentence-id')).toHaveText('F7');
  await expect(page.getByRole('region', { name: 'Sentenças: Documento analisado', exact: true }).locator('.sentence.selected .sentence-id')).toHaveText('A9');
});

test('texto colado, repetição por índice e HTML exibido sem execução', async ({ page }) => {
  await register(page);
  await page.getByRole('button', { name: 'Texto colado', exact: true }).click();
  const sentence = 'A pesquisa compara conteúdos em português.';
  await page.getByLabel('Texto fonte', { exact: true }).fill(sentence);
  await page.getByLabel('Texto analisado', { exact: true }).fill(sentence + ' ' + sentence + ' Texto <script>window.__HTS_XSS=1</script>');
  await compare(page, 200);
  await expect(page.getByRole('heading', { name: 'Relações entre os conteúdos' })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Sentenças: Documento analisado', exact: true }).locator('.sentence')).toHaveCount(3);
  await page.getByRole('button', { name: /^Selecionar F1, A2,/ }).click();
  await expect(page.getByRole('region', { name: 'Sentenças: Documento analisado', exact: true }).locator('.sentence.selected .sentence-id')).toHaveText('A2');
  expect(await page.evaluate(() => '__HTS_XSS' in window)).toBe(false);
});

test('arquivo incompatível e entrada vazia falham sem resultado fabricado', async ({ page }) => {
  await register(page);
  await page.getByLabel('Arquivo fonte', { exact: true }).setInputFiles({ name: 'falso.pdf', mimeType: 'application/pdf', buffer: Buffer.from('Não é PDF.') });
  await page.getByLabel('Arquivo analisado', { exact: true }).setInputFiles({ name: 'valido.txt', mimeType: 'text/plain', buffer: Buffer.from('Uma pesquisa válida.') });
  await compare(page, 415);
  await expect(page.locator('main .error[role="alert"]')).toContainText('tipo real');
  await expect(page.getByRole('heading', { name: 'Relações entre os conteúdos' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Texto colado', exact: true }).click();
  await page.getByLabel('Texto fonte', { exact: true }).fill('   ');
  await page.getByLabel('Texto analisado', { exact: true }).fill('Uma pesquisa válida.');
  await compare(page, 422);
  await expect(page.locator('main .error[role="alert"]')).toContainText('sem texto');
  await page.getByRole('button', { name: 'Dois arquivos', exact: true }).click();
  const folder = process.env.HTS_FIXTURE_DIR ?? '../core/artifacts/ci/fixtures';
  await page.getByLabel('Arquivo fonte', { exact: true }).setInputFiles(folder + '/corrompido.docx');
  await page.getByLabel('Arquivo analisado', { exact: true }).setInputFiles({ name: 'valido.txt', mimeType: 'text/plain', buffer: Buffer.from('Uma pesquisa válida.') });
  await compare(page, 422);
  await expect(page.locator('main .error[role="alert"]')).toContainText('extrair texto');
  const filename = '<img src=x onerror=window.__HTS_NAME=1>.txt';
  await page.getByLabel('Arquivo fonte', { exact: true }).setInputFiles({ name: filename, mimeType: 'text/plain', buffer: Buffer.from('Uma pesquisa válida.') });
  await page.getByLabel('Método / apresentação').selectOption('lexical');
  await compare(page, 200);
  await expect(page.getByRole('heading', { name: 'Relações entre os conteúdos' })).toBeVisible();
  await expect(page.locator('.document-names')).toContainText(filename);
  expect(await page.evaluate(() => '__HTS_NAME' in window)).toBe(false);
  await expect(page.locator('.document-names img')).toHaveCount(0);
});
